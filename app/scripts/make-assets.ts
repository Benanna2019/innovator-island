/**
 * Generates our own background, frame and a green-screen test fixture. Nothing here comes from the AWS CloudFront
 * assets. Run `pnpm assets` after changing it. Output: src/domain/image/assets.generated.ts and tests/fixtures/.
 */
import { Jimp } from 'jimp'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

export const PHOTO_WIDTH = 640
export const PHOTO_HEIGHT = 480

function paint(img: InstanceType<typeof Jimp>, x0: number, y0: number, x1: number, y1: number, color: number) {
  for (let y = Math.max(0, y0); y < Math.min(img.bitmap.height, y1); y++) {
    for (let x = Math.max(0, x0); x < Math.min(img.bitmap.width, x1); x++) img.setPixelColor(color, x, y)
  }
}

const rgba = (r: number, g: number, b: number, a = 255) => ((r << 24) | (g << 16) | (b << 8) | a) >>> 0

async function background() {
  const img = new Jimp({ width: PHOTO_WIDTH, height: PHOTO_HEIGHT, color: 0xffffffff })
  for (let y = 0; y < PHOTO_HEIGHT; y++) {
    const t = y / PHOTO_HEIGHT
    paint(img, 0, y, PHOTO_WIDTH, y + 1, rgba(Math.round(250 - 120 * t), Math.round(190 - 60 * t), Math.round(120 + 90 * t)))
  }
  // Sun
  for (let y = 0; y < PHOTO_HEIGHT; y++) {
    for (let x = 0; x < PHOTO_WIDTH; x++) {
      if ((x - 480) ** 2 + (y - 130) ** 2 < 52 ** 2) img.setPixelColor(rgba(255, 236, 170), x, y)
    }
  }
  // Rolling hills and a roller coaster track
  for (let x = 0; x < PHOTO_WIDTH; x++) {
    const hill = 360 + Math.round(26 * Math.sin(x / 70) + 14 * Math.sin(x / 23))
    paint(img, x, hill, x + 1, PHOTO_HEIGHT, rgba(38, 92, 84))
    const track = 250 + Math.round(60 * Math.sin(x / 55))
    paint(img, x, track, x + 1, track + 5, rgba(120, 42, 30))
    if (x % 28 === 0) paint(img, x, track + 5, x + 3, hill, rgba(120, 42, 30))
  }
  return img.getBuffer('image/png')
}

async function frame() {
  const img = new Jimp({ width: PHOTO_WIDTH, height: PHOTO_HEIGHT, color: 0x00000000 })
  const border = 18
  const ink = rgba(15, 76, 92)
  paint(img, 0, 0, PHOTO_WIDTH, border, ink)
  paint(img, 0, PHOTO_HEIGHT - border * 2, PHOTO_WIDTH, PHOTO_HEIGHT, ink)
  paint(img, 0, 0, border, PHOTO_HEIGHT, ink)
  paint(img, PHOTO_WIDTH - border, 0, PHOTO_WIDTH, PHOTO_HEIGHT, ink)
  // Ticket-stub bar along the bottom, built from blocks so no font is needed.
  for (let i = 0; i < 16; i++) {
    paint(img, 40 + i * 36, PHOTO_HEIGHT - 30, 40 + i * 36 + 20, PHOTO_HEIGHT - 12, i % 2 ? rgba(247, 245, 238) : rgba(244, 177, 54))
  }
  return img.getBuffer('image/png')
}

/** A flat green screen with a magenta and navy "person" on it. The subject must survive keying. */
async function greenscreen() {
  const w = 64
  const h = 48
  const img = new Jimp({ width: w, height: h, color: rgba(20, 200, 40) })
  paint(img, 24, 8, 40, 24, rgba(200, 40, 140))
  paint(img, 18, 24, 46, 48, rgba(20, 30, 110))
  return img.getBuffer('image/png')
}

function write(path: string, data: Buffer | string) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, data)
}

const [bg, fr, gs] = await Promise.all([background(), frame(), greenscreen()])
write('tests/fixtures/greenscreen.png', gs)
write(
  'src/domain/image/assets.generated.ts',
  `// Generated by scripts/make-assets.ts. Our own simple art, not the AWS CloudFront files.\n` +
    `export const PHOTO_WIDTH = ${PHOTO_WIDTH}\nexport const PHOTO_HEIGHT = ${PHOTO_HEIGHT}\n` +
    `export const BACKGROUND_PNG_BASE64 = '${bg.toString('base64')}'\n` +
    `export const FRAME_PNG_BASE64 = '${fr.toString('base64')}'\n`,
)
console.log('assets written', { background: bg.length, frame: fr.length, greenscreen: gs.length })
